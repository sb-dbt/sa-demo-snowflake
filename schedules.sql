-- Run by the merge workflow after the prod dbt project object deploys.
-- The scheduled build keeps prod data fresh and keeps Slim CI state inside its 14-day window.
ALTER TASK IF EXISTS SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD.RUN_SA_DEMO_FULL SUSPEND;

CREATE OR ALTER TASK SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD.RUN_SA_DEMO_FULL
  WAREHOUSE = TRANSFORMING
  SCHEDULE = '12 hours'
  AS
    EXECUTE DBT PROJECT SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD.SA_DEMO_SNOWFLAKE
      ARGS = 'build --target prod';

ALTER TASK IF EXISTS SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD.RUN_SA_DEMO_FULL RESUME;
