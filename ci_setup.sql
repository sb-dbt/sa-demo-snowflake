-- One-time Snowflake setup for CI/CD of sb-dbt/sa-demo-snowflake.
-- Follows the dbt Projects on Snowflake advanced CI/CD tutorial (OIDC service user,
-- dedicated CI role, per-PR databases). Run as ACCOUNTADMIN (CREATE DATABASE / EXECUTE TASK
-- on account need it); already applied.

-- CI role: owns SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD (granted separately by the database owner)
GRANT USAGE ON DATABASE SB_SNOWFLAKE_DBT_TESTING TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON WAREHOUSE TRANSFORMING TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON INTEGRATION GG_DBT_DEPS_EAI TO ROLE SA_DEMO_CI_ROLE;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE SA_DEMO_CI_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SA_DEMO_CI_ROLE;

-- Read access to the project's sources
GRANT USAGE ON DATABASE RAW TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON SCHEMA RAW.TPCH_NOW TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW.TPCH_NOW TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA RAW.TPCH_NOW TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON SCHEMA RAW.TPCH_SF001 TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW.TPCH_SF001 TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA RAW.TPCH_SF001 TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE SA_DEMO_CI_ROLE;
GRANT USAGE ON SCHEMA ANALYTICS.RAW TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ANALYTICS.RAW TO ROLE SA_DEMO_CI_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA ANALYTICS.RAW TO ROLE SA_DEMO_CI_ROLE;

-- Developers (TRANSFORMER) read prod; only the CI role writes it
GRANT USAGE ON SCHEMA SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SB_SNOWFLAKE_DBT_TESTING.SA_DEMO_PROD TO ROLE TRANSFORMER;
